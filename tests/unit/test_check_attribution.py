"""Tests for the commit attribution check (spec S1-R8-S1)."""

from __future__ import annotations

import importlib.util
import io
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location(
    "check_attribution", REPO / "scripts" / "check_attribution.py"
)
assert _spec is not None
assert _spec.loader is not None
check_attribution = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check_attribution)
offending = check_attribution.offending


def test_offending_detects_both_forms():
    messages = {
        "aaa": "feat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
        "bbb": "fix: y\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
        "ccc": "docs: z\n\nco-authored-by: claude <x@y>",
    }
    assert offending(messages) == ["aaa", "bbb", "ccc"]


def test_clean_messages_pass():
    messages = {
        "aaa": "feat: add grilling\n\nCo-Authored-By: Jane Doe <jane@example.com>",
        "bbb": "docs: mention that Claude Code is a supported harness",
    }
    assert offending(messages) == []


def test_option_like_range_is_rejected():
    with pytest.raises(ValueError, match="revision range"):
        check_attribution.read_messages("--output=/tmp/x")


def test_other_agents_are_caught():
    messages = {
        "a": "feat: x\n\nCo-authored-by: Copilot <copilot@github.com>",
        "b": "fix: y\n\nGenerated by Cursor",
        "c": "docs: z\n\nCo-Authored-By: Codex <codex@openai.com>",
        "d": "test: w\n\nCo-authored-by: Gemini <noreply@google.com>",
    }
    assert offending(messages) == ["a", "b", "c", "d"]


def test_mentioning_a_harness_is_fine():
    messages = {"a": "feat: support Cursor, Codex and Gemini CLI as harnesses"}
    assert offending(messages) == []


def test_stdin_text_is_checked(monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setattr(
        "sys.stdin", io.StringIO("Body\n\n🤖 Generated with Claude Code\n")
    )
    assert check_attribution.check_text_from_stdin() == ["stdin"]
